-- 온라인 QR 퀴즈 서바이벌 - Supabase 데이터베이스 설정
-- Supabase 대시보드 → SQL Editor 에서 이 스크립트를 "전체" 실행하세요.
-- (여러 번 실행해도 안전합니다. 이미 있는 것은 건너뜁니다.)

-- 1) 테이블 생성
create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  question text not null,
  options jsonb not null default '[]'::jsonb,
  answer int not null,
  created_at timestamptz not null default now()
);

create table if not exists public.players (
  id uuid primary key,
  name text not null,
  alive boolean not null default true,
  answer int,
  result text,
  correct_answer text,
  created_at timestamptz not null default now()
);

create table if not exists public.game (
  id int primary key default 1,
  status text not null default 'waiting',
  current_number int not null default 0,
  question_order jsonb not null default '[]'::jsonb,
  target_remaining int not null default 5,
  shuffle boolean not null default true,
  current jsonb
);

-- 2) 실시간 publication 존재 확인 후 생성
do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
end $$;

-- 3) 테이블을 실시간 구독에 추가 (이미 있으면 건너뜀 → 오류로 중단되지 않음)
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'questions') then
    alter publication supabase_realtime add table public.questions;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'players') then
    alter publication supabase_realtime add table public.players;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'game') then
    alter publication supabase_realtime add table public.game;
  end if;
end $$;

-- 4) 간단한 방식을 위해 RLS(행 수준 보안) 비활성화
--    정식 행사에서 정답 보안이 필요하면 RLS + 정책을 사용해야 합니다.
alter table public.questions disable row level security;
alter table public.players disable row level security;
alter table public.game disable row level security;

-- 5) 기본 게임 상태 행 생성
insert into public.game (id, status, current_number, question_order, target_remaining, shuffle, current)
values (1, 'waiting', 0, '[]'::jsonb, 5, true, null)
on conflict (id) do nothing;
