-- 1) 테이블 생성
create table if not exists questions (
  id bigint generated by default as identity primary key,
  question text not null,
  options jsonb not null default '[]'::jsonb,
  answer int not null,
  created_at timestamptz not null default now()
);

create table if not exists players (
  id uuid primary key,
  name text not null,
  alive boolean not null default true,
  answer int,
  result text,
  correct_answer text,
  created_at timestamptz not null default now()
);

create table if not exists game (
  id int primary key default 1,
  status text not null default 'waiting',
  current_number int not null default 0,
  question_order jsonb not null default '[]'::jsonb,
  target_remaining int not null default 5,
  shuffle boolean not null default true,
  current jsonb
);

-- 2) 실시간(Realtime) 구독 활성화
--    ※ 이미 추가된 경우 "already member of publication" 오류가 나면 무시하면 됩니다.
alter publication supabase_realtime add table questions;
alter publication supabase_realtime add table players;
alter publication supabase_realtime add table game;

-- 3) 간단한 방식을 위해 RLS(행 수준 보안) 비활성화
--    정식 행사에서 정답 보안이 필요하면 RLS + 정책을 사용해야 합니다.
alter table questions disable row level security;
alter table players disable row level security;
alter table game disable row level security;

-- 4) 기본 게임 상태 행 생성
insert into game (id) values (1)
on conflict (id) do nothing;
